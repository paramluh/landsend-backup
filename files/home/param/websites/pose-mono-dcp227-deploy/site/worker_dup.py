def vc_on(req):
    """10-27 user: the voice clip prompt toggle (page: prompt.voice_clip; also accepted top level / in params). Absent (requests from before
    the toggle) = on, exactly as before."""
    v = (req.get("prompt") or {}).get("voice_clip", req.get("voice_clip", (req.get("params") or {}).get("voice_clip")))
    return True if v is None else v in (True, 1, "1", "true")


def empty_pre():
    """voice clip prompt off -> the EMPTY system block (P = 5) = the poseduplex trainer's no-clip row (data_aloe_v2.prefix_v2 /
    data_aloe_posedup.prefix_third with the voice draw false: segs [{"kind": "text", "track": 1, "ids": []}] -> sysprompt.build_prefix),
    built by prompts_ppm.build_prefix with no clip and no text (the same segment list; the live demo's 'no voice clip')."""
    spx = PR.build_prefix("", None, prose=False)[0]
    assert int(spx["P"]) == 5, ("empty system block must be 5 positions", spx["P"])
    return {"P": 5, "ids": spx["ids"], "depth": spx["depth"], "present": spx["present"]}


def pre_digest(pre):
    """10-27: read-only digest of a system block (summary.sys_block): P + sha1 of ids / depth / present."""
    return {"P": int(pre["P"]), "sha1": hashlib.sha1(b"".join(np.ascontiguousarray(pre[k]).tobytes() for k in ("ids", "depth", "present"))).hexdigest()[:16]}


