    def run_duo(self, rd, req, st):
        """BOTH SIDES GENERATED (user rule conversation-gens-duo; 10-26 dupui). Two LivePPM states on the one weight copy: state 0 plays side
        K (= B, the avatar), state 1 plays side 1 - K (= A); each is set up exactly like the replay path's B for its own side (its own system
        block / voice clip, its own real opening forced: lane frames < N + CD, Mimi codes + pose frames < N) and its channel A = the OTHER
        state's voice. prefill_line "aligned" (default; main 10-26): A samples t < N x 1920 = the partner's real opening audio ALIGNED (as
        in training; the engine's live-demo prefill A-mute is off); the partner's generated audio (code frames g >= N) arrives DELAY = 5832
        samples (243 ms) late, i.e. at A sample g x 1920 + 5832, so A samples [N x 1920, N x 1920 + 5832) are silent; the delay starts at the
        first generated step f = N + CD. "delayed" = gen_pd.py: A(t) = partner(t - 5832) everywhere (real opening, then generated). Seeds:
        the state of side k = seed + 10 k (= gen_pd). Sampling, engine and forcing = the replay path (unchanged)."""
        rid = req["run_id"]
        pr = {k: v for k, v in (req.get("params") or {}).items() if k not in RUN_KEYS and k not in LP.GRAMMAR_GONE}   # 10-28 USER ORDER: no lane grammar, ever: legacy grammar keys dropped silently
        bad = [k for k in pr if k not in LP.PARAMS]
        if bad:
            raise ValueError(f"unknown engine knobs: {bad}")
        clean, probs = LP.validate(pr)
        params = dict(DEF, **clean)
        seed = int(req.get("seed") or 0) or int.from_bytes(os.urandom(3), "little") + 1
        clip_s = min(max(float(req.get("clip_s") or 20.0), 1.0), 118.0)
        cid = str(req.get("conv") or "c0")
        if cid not in [f"c{i}" for i in range(8)]:
            raise ValueError(f"both-sides generation needs a two-sided conversation (c0..c7), not {cid}: Call 1086 is replay only")
        K = int(req.get("side") or 0)
        assert K in (0, 1), f"side {K}"
        line = str(req.get("prefill_line") or (req.get("params") or {}).get("prefill_line") or (req.get("ui") or {}).get("prefill_line") or "aligned")
        assert line in ("aligned", "delayed"), f"prefill_line {line}"
        person = str(req.get("person") or "heldout_02")
        pf = req.get("prefill") or {}
        pfs = min(max(float(pf.get("s") or 0.0), 0.0), MAX_PF_S)
        use_pose, use_audio, use_words = bool(pf.get("pose", True)), bool(pf.get("audio", True)), bool(pf.get("words", True))
        notes = []
        vc = vc_on(req)                                                 # 10-27 user: voice clip prompt toggle (off -> both states' blocks empty)
        z, cj = self.conv(cid)
        sides = (K, 1 - K)
        E = (self.eng, self.eng2)
        N = min(min(len(z[f"laneB_{k}"]) for k in sides) - CD, 2 * int(round(pfs / 0.16)) + 2) if (pfs > 0 and (use_pose or use_audio or use_words)) else 0
        S = []
        for s, k in enumerate(sides):
            lb, db, pb = z[f"laneB_{k}"], z[f"depB_{k}"], z[f"pdepB_{k}"]
            ppose = (pb[CD:CD + N] - OFF[None]) if (use_pose and N) else None
            pcodes = (db[CD:CD + N] - OFF[None]) if (use_audio and N) else None
            lane_f = None
            if N and use_words:
                lane_f = np.asarray(lb[:N + CD], np.int64)
            elif N and use_audio:
                lane_f = np.full(N + CD, PAD, np.int64)
                if s == 0:
                    notes.append("prefill lane PAD (words off, audio on: off-distribution)")
            if ppose is not None:
                assert ppose.min() >= 0 and ppose.shape == (N, 32), ("pose prefill", k, ppose.shape, int(ppose.min()))
            if pcodes is not None:
                assert pcodes.min() >= 0 and pcodes.shape == (N, 32), ("codes prefill", k, pcodes.shape, int(pcodes.min()))
            pre = ({"P": int(z[f"pre_ids_{k}"].shape[1]), "ids": z[f"pre_ids_{k}"], "depth": z[f"pre_depth_{k}"], "present": z[f"pre_present_{k}"]}
                   if vc else empty_pre())
            S.append({"k": k, "pre": pre, "P": int(pre["P"]), "ppose": ppose, "pcodes": pcodes, "lane_f": lane_f, "seed": seed + 10 * k,
                      "side_name": cj["dirs"][k].get("chan_B_data_side") or ("assistant" if k == 0 else "user"),
                      "tok": [], "b": [], "pose": [], "mimi": []})
        gen_fr = int(round(clip_s * 12.5))
        nf = N + CD + gen_fr
        cap = min(E[0].n_fr, E[1].n_fr) - 4
        if nf > cap:
            notes.append(f"clip capped at {(cap - N - CD) / 12.5:.1f} s (engine buffer)")
            nf = cap
        NS = N * SPF
        L = nf * SPF + LOOK + 2 * SPF
        part = [np.zeros(L, np.float32) for _ in (0, 1)]               # part[s] = what state s SAYS (its partner hears it): real opening, then generated
        heard = [np.zeros(L, np.float32) for _ in (0, 1)]              # heard[s] = channel A exactly as written to state s
        for s in (0, 1):
            stem = z[f"stem_{S[s]['k']}"].astype(np.float32)
            assert len(stem) >= NS, ("stem shorter than the opening", S[s]["k"], len(stem), NS)
            part[s][:NS] = stem[:NS]
        filled = [NS, NS]

        def a_of(s, lo, hi):
            o, x = 1 - s, np.zeros(hi - lo, np.float32)
            if line == "aligned":
                b_ = min(hi, NS)
                if b_ > lo:
                    x[:b_ - lo] = part[o][lo:b_]                          # the partner's real opening, aligned (as in training)
                a0 = max(lo, NS + DELAY)
            else:
                a0 = max(lo, DELAY)
            if hi > a0:
                assert hi - DELAY <= filled[o], ("partner audio not yet available", s, lo, hi, filled[o])
                x[a0 - lo:] = part[o][a0 - DELAY:hi - DELAY]
            return x

        live = (getattr(self, "feed", None) is not None and self.feed.enabled() and req.get("stream") is True
                and not req.get("no_live"))                     # 10-26 user: never livestream unless the request asks for it
        t0 = time.time()
        with torch.no_grad():
            bad2 = []
            for s in (0, 1):
                E[s].start(S[s]["pre"], S[s]["seed"], params, pose_prefill=S[s]["ppose"])
                E[s].a_mute = 0                                             # duo: each state hears the partner's real opening (no live-demo user mute)
                bad2 += list(E[s].set_params(params)[1] or [])
            if live:
                self.feed.put("start", rid, json.dumps({"type": "start", "session": rid, "model": "genweb-dup", "voice": person, "fps": 12.5,
                                                         "person": person, "prefill_s": 0.0, "record": f"{rd}/avatar.mp4",
                                                         **({"weights": "vansh"} if req.get("video_weights") == "vansh" else {})}))
            wrote = [0, 0]
            dec = [None, None]
            for f in range(nf):
                need = (f + 1) * SPF + LOOK
                for s in (0, 1):
                    x = a_of(s, wrote[s], need)
                    E[s].write_a(wrote[s], x)
                    heard[s][wrote[s]:need] = x
                    wrote[s] = need
                    frc = None
                    lf, pc = S[s]["lane_f"], S[s]["pcodes"]
                    if lf is not None and f < N + CD:                       # = the replay path's forcing, per state
                        g = f - CD
                        frc = (int(lf[f]), (pc[g] + OFF) if (pc is not None and 0 <= g < N) else None, None)
                    dec[s] = E[s].step(S[s]["P"] + f, force=frc)
                for s in (0, 1):
                    tok, _, _, y = E[s].result(S[s]["P"] + f, dec[s])
                    S[s]["tok"].append(tok)
                    if y is not None:
                        S[s]["b"].append(y)
                        g = f - CD
                        if g >= N:                                          # generated frame g -> the partner hears it DELAY later
                            part[s][g * SPF:(g + 1) * SPF] = y
                            filled[s] = (g + 1) * SPF
                    cf = f - CD
                    if cf >= 0:
                        S[s]["pose"].append(list(E[s].last_pose))
                        S[s]["mimi"].append(list(E[s].last_codes))
                        if s == 0 and live and y is not None:
                            seg = y if len(y) == SPF else np.zeros(SPF, np.float32)
                            pcm = np.clip(seg * 32767, -32768, 32767).astype("<i2").tobytes()
                            self.feed.put("f", rid, json.dumps({"type": "f", "session": rid, "f": cf, "t": round(cf * 0.08, 3), "pose": S[0]["pose"][-1],
                                                                "mimi": S[0]["mimi"][-1], "pcm_b64": base64.b64encode(pcm).decode("ascii")}))
                if f % 25 == 0:
                    if os.path.exists(f"{rd}/CANCEL"):
                        if live:
                            self.feed.put("end", rid, json.dumps({"type": "end", "session": rid}))
                        raise RuntimeError("cancelled")
                    el = time.time() - t0
                    jwrite(f"{rd}/status.json", dict(st, progress=round(f / nf, 3), frames_done=f, frames_total=nf,
                                                     ms_per_frame=round(1e3 * el / max(1, f), 1), msg=f"generating both sides {f}/{nf} frames"))
            if live:
                self.feed.put("end", rid, json.dumps({"type": "end", "session": rid}))
        wall = time.time() - t0
        out = []
        for s in (0, 1):
            pose = np.asarray(S[s]["pose"], np.int64)
            mimi = np.asarray(S[s]["mimi"], np.int64)
            tok = np.asarray(S[s]["tok"], np.int64)
            assert len(pose) and pose.min() >= 0 and mimi.min() >= 0, ("pose / codes missing", s)
            if S[s]["ppose"] is not None:
                assert (pose[:N] == S[s]["ppose"]).all(), ("pose prefill != real tokens", s)
            if S[s]["pcodes"] is not None:
                assert (mimi[:N] == S[s]["pcodes"]).all(), ("audio prefill != real codes", s)
            if S[s]["lane_f"] is not None:
                assert (tok[:N + CD] == S[s]["lane_f"][:N + CD]).all(), ("lane prefill != real lane", s)
            b = np.concatenate(S[s]["b"]).astype(np.float32) if S[s]["b"] else np.zeros(0, np.float32)
            out.append((pose, mimi, tok, b))
        pose, mimi, tok, b = out[0]
        n = len(pose)
        a_fed = heard[0][:len(b)]
        a_own = out[1][3]
        import soundfile as sf
        for name, w in (("b", b), ("a", a_fed), ("mix", a_fed + b), ("a_own", a_own)):
            sf.write(f"{rd}/{name}.wav.part.wav", np.clip(w, -1, 1), 24000, subtype="PCM_16")
            os.replace(f"{rd}/{name}.wav.part.wav", f"{rd}/{name}.wav")
        pf_fr = N + CD if S[0]["lane_f"] is not None else 0
        t_end = n / 12.5
        dl_s = DELAY / 24000

        def words(tk, heard_shift):
            bw = LP.IP.lane_words(tk)                                   # {text, frame, t = frame / 12.5}
            ts = [float(q["t"]) + (heard_shift if (line == "delayed" or q["frame"] >= N) else 0.0) for q in bw] if heard_shift else [float(q["t"]) for q in bw]
            return [{"t0": round(ts[i], 2), "t1": round(min(ts[i + 1] if i + 1 < len(ts) else ts[i] + 0.4, ts[i] + 1.5), 2), "w": q["text"],
                     "prefill": bool(q["frame"] < pf_fr)} for i, q in enumerate(bw)]
        wl = [dict(w, ch="B") for w in words(tok, 0.0)]
        wl += [dict(w, ch="A") for w in words(out[1][2], dl_s) if w["t0"] < t_end]   # A's words on the timeline B heard them (a.wav)
        wl.sort(key=lambda x: (x["t0"], x["ch"]))
        jwrite(f"{rd}/words.json", wl)
        np.savez_compressed(f"{rd}/tokens.npz", pose=pose.astype(np.int16), mimi=mimi.astype(np.int16), lane=tok,
                            pose_a=out[1][0].astype(np.int16), mimi_a=out[1][1].astype(np.int16), lane_a=out[1][2])
        self.write_feed(f"{rd}/feed.jsonl", rid, person, 0.0, pose, mimi, b, n)
        jd = (RJOBS_V if req.get("vansh_steps") == 20 else RJOBS_V50) if req.get("video_weights") == "vansh" else RJOBS   # no field = 50 (old)
