def cut(a, b_end, new=""):
    """replace s[start of a : end of b_end (first occurrence after a)] by new."""
    global s
    assert s.count(a) == 1, (MODEL, "cut start", s.count(a), a[:120])
    i = s.index(a)
    j = s.index(b_end, i) + len(b_end)
    s = s[:i] + new + s[j:]


