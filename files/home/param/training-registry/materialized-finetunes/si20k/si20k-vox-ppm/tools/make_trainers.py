def cfg_diff_si20k():
    """the resolved CFG vs the reference run's LOGGED cfg (SI20K_REF_CFG): only run dirs / refs, the schedule length, the data / prompt keys
    and the accumulation layout may differ (else abort)."""
    cur = _flat(json.loads(json.dumps(CFG, default=str)))
    ref = _flat(json.load(open(E("SI20K_REF_CFG"))))
    rows, bad = [], []
    for k in sorted(set(ref) | set(cur)):
        a, b = ref.get(k, "<absent>"), cur.get(k, "<absent>")
        if a != b:
            ok = any(k == x or k.startswith(x + ".") for x in SI20K_ALLOWED)
            rows.append(f"  {'ok ' if ok else 'BAD'} {k}: ref {a} -> si20k {b}")
            if not ok:
                bad.append(k)
    log(f"[cfg-diff] resolved config vs the reference run's logged cfg ({E('SI20K_REF_CFG')}): {len(rows)} keys differ ({len(bad)} outside run dirs / "
        f"schedule length / data + prompt / accumulation), every other key of {len(set(ref) | set(cur))} identical\\n" + "\\n".join(rows))
