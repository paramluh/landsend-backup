def run_micro(model, b, rot, dos, grad, info=None, nano=None):
    """si20k-txt: forward (text in + the user's Voxtral latents, text out) -> loss = the text CE only (PPM's factorised weights), ONE
    backward. dos / nano unused (no decoder). -> (text stats vector, loss value, {})."""
    assert not dos and nano is None, "si20k-txt: no decoder"
    with (torch.enable_grad() if grad else torch.no_grad()):
        out = model(b, rot, rot, info=info, **(b.get("fwd") or {}))
    assert {"text", "text_stats"} <= set(out) <= {"text", "text_stats", "h", "e", "hn"}, ("text-out model: text terms only", sorted(out))
    loss = out["text"]
    v = text_vec(b, out["text_stats"])
    if grad:
        loss.backward()
    dvc = loss.device
    v = torch.stack([torch.as_tensor(x, device=dvc).double().reshape(()) for x in v]).tolist()
    if b.get("dummy", False):                                     # aloe: a dummy micro contributes nothing to any statistic
        assert float(loss) == 0.0, ("dummy micro with a non-zero loss", float(loss))
        v = [0.0] * len(v)
    return v, float(loss), {}


@torch.no_grad()
def micro_losses(model, mic, rot, dev, lat):
    """one micro with MICRO-level token normalisers -> ([text CE], [text targets]) (si20k-txt: the only loss term)."""
    oc = np.asarray(mic["own"]).sum(0)
    b = prep(mic, dev, oc[0], 1.0, lat=lat)
    out = model(b, rot, rot)
    return [float(out["text"])], [float(oc[0])]


def pack_loss_check(model, b, rot, dev, lat):
    """run C's S4_PACK_LOSSCHECK (text term only): the packed text loss == the token-weighted mean of the standalone conversations'."""
    model.eval()
    singles = b["singles"]
    Pv, _ = micro_losses(model, b, rot, dev, lat)
    K = len(singles)
    t = torch.tensor([float(K)], device=dev); dist.all_reduce(t, op=dist.ReduceOp.MAX); Kmax = int(t)
    num, den = [0.0], [0.0]
    for k in range(Kmax):
        L, N = micro_losses(model, singles[k if k < K else 0], rot, dev, lat)
        if k < K:
            num[0] += N[0] * L[0]; den[0] += N[0]
    model.train()
    exp = [num[0] / den[0]]
    err = [abs(Pv[0] - exp[0]) / max(abs(exp[0]), 1e-12)]
    return Pv, exp, err, K


